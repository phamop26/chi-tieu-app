export function addStrings(extra) {
  for (const l of Object.keys(extra)) Object.assign(S[l], extra[l]);
}
export function setLang(l) { lang = S[l] ? l : 'vi'; document.documentElement.lang = lang; }
export function getLang() { return lang; }
export const LOCALES = { vi: 'vi-VN', en: 'en-US', fr: 'fr-FR' };
export function locale() { return LOCALES[lang]; }

export function t(key, params) {
  let s = (S[lang] && S[lang][key]) ?? S.vi[key] ?? key;
  if (params && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
  return s;
}

export function catName(cat) {
  if (!cat) return t('noSuggestion');
  if (cat.name) return cat.name;
  return (CAT_NAMES[cat.id] && CAT_NAMES[cat.id][lang]) || cat.id;
}
